def href(name):
    return urllib.parse.quote(name)


def lessons():
    out = {}
    for p in sorted(glob.glob(os.path.join(REPO, "*.md"))):
        name = os.path.basename(p)
        m = re.match(r"^(\d{2})-(.+)\.md$", name)
        if not m:
            continue
        text = open(p, encoding="utf-8").read()
        title = re.sub(r"^#\s*课时\d+[：:]\s*", "", text.split("\n", 1)[0].strip())
        src = re.search(r"^来源：\[(.*?)\]", text, re.M)
        skip = False
        secs = []
        for line in text.split("\n"):
            if line.startswith("```"):
                skip = not skip
                continue
            if skip or not line.startswith("## "):
                continue
            h = line[3:].strip()
            if h in {"前言", "学习目标", "课程目标", "继续学习", "评价反馈"}:
                continue
            secs.append(h)
        out[int(m.group(1))] = (name, title, src.group(1) if src else "", secs)
    return out


